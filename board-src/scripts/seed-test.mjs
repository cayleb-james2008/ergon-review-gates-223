#!/usr/bin/env node
// Prints SQL (stdout) that seeds 19 TEST lines (code A..S, sort_order 1..19) and ~14 synthetic TEST jobs.
// Apply as ONE transaction so the pre-check and the inserts cannot be separated:
//   node scripts/seed-test.mjs | psql -v ON_ERROR_STOP=1 "$DATABASE_URL"
// The generated SQL REFUSES (psql exits non-zero, nothing is written) when lines or
// entries holds any row with is_test = false. Idempotent; never deletes anything.
// No seed file is committed: the SQL is generated here at run time. Deterministic.

if (process.argv.includes('--help') || process.argv.includes('-h')) {
  process.stderr.write('usage: node scripts/seed-test.mjs | psql -v ON_ERROR_STOP=1 <connection-url>\n');
  process.exit(0);
}

const labels = 'ABCDEFGHIJKLMNOPQRS'.split('');

// [line code, title, details, initials, status]
const jobs = [
  ['A', 'TEST Acme Widgets (fictional)', 'pallet of sprockets', 'QA', 'open'],
  ['A', 'TEST Bluebird Tooling', 'wrap and label', 'QA', 'hold'],
  ['B', 'TEST Cobalt Candles', 'fragile, 3 cartons', 'ZZ', 'ready'],
  ['C', 'TEST Dummy Dairy Co', 'chilled, ship today', 'QA', 'open'],
  ['D', 'TEST Evergreen Imaginary Ltd', 'customer pickup 3pm', 'ZZ', 'done'],
  ['D', 'TEST Foobar Freight', 'waiting on paperwork', 'QA', 'hold'],
  ['F', 'TEST Gadget Garden', 'rework labels', 'ZZ', 'open'],
  ['G', 'TEST Hypothetical Hardware', 'ready for loading', 'QA', 'ready'],
  ['H', 'TEST Imaginary Ink', 'short pick, 2 units', 'ZZ', 'open'],
  ['K', 'TEST Juniper Jigs (not real)', 'done and stacked', 'QA', 'done'],
  ['M', 'TEST Kestrel Kits', 'mixed pallet', 'ZZ', 'ready'],
  ['M', 'TEST Lorem Logistics', 'hold for count', 'QA', 'hold'],
  ['P', 'TEST Mockingbird Metals', 'urgent', 'ZZ', 'open'],
  ['Q', 'TEST Nowhere Notions', 'ready to wrap', 'QA', 'ready'],
];

const q = (s) => "'" + s.replaceAll("'", "''") + "'";
const entryId = (i) => `5eed0000-0000-4000-8000-${String(i + 1).padStart(12, '0')}`;

const lineValues = labels.map((l, i) => `(${q(l)}, ${i + 1})`).join(',\n    ');
const jobValues = jobs
  .map((j, i) => `(${q(entryId(i))}::uuid, ${q(j[0])}, ${q(j[1])}, ${q(j[2])}, ${q(j[3])}, ${q(j[4])}, ${i})`)
  .join(',\n    ');

process.stdout.write(`-- generated by scripts/seed-test.mjs: synthetic TEST data only
begin;

do $seed$
declare n_lines bigint; n_entries bigint;
begin
  select count(*) into n_lines   from ergon_warehouse.lines   where is_test is distinct from true;
  select count(*) into n_entries from ergon_warehouse.entries where is_test is distinct from true;
  if n_lines > 0 or n_entries > 0 then
    raise exception 'SEED REFUSED: ergon_warehouse holds non-test rows (lines=%, entries=%); this script only seeds an empty or test-only database', n_lines, n_entries;
  end if;
end
$seed$;

-- No unique index on code is assumed (the live table may have none): guard with WHERE NOT EXISTS.
-- Every NOT NULL column is set explicitly: the live tables may have no defaults.
insert into ergon_warehouse.lines (id, code, sort_order, created_at, is_test)
select gen_random_uuid(), v.code, v.sort_order, now(), true
from (values
    ${lineValues}
) as v(code, sort_order)
where not exists (select 1 from ergon_warehouse.lines l where l.code = v.code);

insert into ergon_warehouse.entries
  (id, line_id, title, details, photo_metadata, revision, created_at, updated_at, tags, initials, status, is_test)
select v.id,
       (select l.id from ergon_warehouse.lines l where l.code = v.code order by l.id limit 1),
       v.title, v.details, '[]'::jsonb, 1,
       now() - interval '1 hour' + v.n * interval '1 minute',
       now() - interval '1 hour' + v.n * interval '1 minute',
       '{}'::text[], v.initials, v.status, true
from (values
    ${jobValues}
) as v(id, code, title, details, initials, status, n)
where not exists (select 1 from ergon_warehouse.entries e where e.id = v.id);

commit;
`);
